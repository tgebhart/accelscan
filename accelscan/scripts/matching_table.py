"""Alias-matching conventions table for the methods section.

The conventions were previously described in running prose with inline regular
expressions, which is dense and hard to check. This emits them as a rules table
with a matching and a non-matching exemplar each --- and, because the exemplars are
run through the live matcher before the table is written, the table cannot drift
from the code. A row whose exemplars stop behaving as documented fails the build.

    python -m accelscan.scripts.matching_table            # verify + write table
    python -m accelscan.scripts.matching_table --stdout

Output: docs/tables/matching_conventions.tex, \\input by docs/methods.tex.
"""

import argparse
import sys
from pathlib import Path

from accelscan.registry import load_registry

OUT_PATH = Path('docs/tables/matching_conventions.tex')

# (convention, alias, passage, model id the passage must resolve to or None for
# "no model"). A convention repeated on consecutive rows prints its label once.
# Every passage carries GPU context, so a row that resolves to nothing does so
# because of the convention under test rather than an unsatisfied context gate.
ROWS = [
    ('Word boundary, optional plural', 'V100',
     'eight V100s on the GPU cluster', 'nvidia-v100'),
    ('Word boundary, optional plural', 'V100',
     'the CV100x sensor on the GPU node', None),
    ('Separator optional', 'RTX 3090',
     'an RTX-3090 card', 'nvidia-geforce-rtx-3090'),
    ('Separator optional', 'Tesla V100',
     'a TeslaV100 node', 'nvidia-v100'),
    ('Longest span wins', 'RTX 3090 Ti',
     'an RTX 3090 Ti card', 'nvidia-geforce-rtx-3090-ti'),
    ('Upper-case alias is case-sensitive', 'K80',
     'K80 cards in a GPU node', 'nvidia-k80'),
    ('Upper-case alias is case-sensitive', 'K80',
     'k80 cards in a gpu node', None),
    ('Vendor-led alias is not', 'NVIDIA L4',
     'a Nvidia L4 GPU', 'nvidia-l4'),
    ('Tier-B alias needs context', 'A100',
     'we used an A100 GPU for training', 'nvidia-a100'),
    ('Tier-B alias needs context', 'A100',
     'A100 antibody staining of the section', None),
]


def kept(reg, text: str) -> set[str]:
    return {m.model_id for m in reg.match_paragraph(text)
            if not m.gate_required or m.gate_ok}


def verify(reg) -> None:
    """Refuse to emit a table the matcher does not actually produce."""
    for name, alias, passage, want in ROWS:
        models = {i for i in kept(reg, passage)
                  if reg.models[i].kind == 'model'}
        if want is None and models:
            raise SystemExit(f'{name!r}: {passage!r} was expected to resolve to no '
                             f'model but matched {sorted(models)}')
        if want is not None and models != {want}:
            raise SystemExit(f'{name!r}: {passage!r} resolved to {sorted(models)}, '
                             f'expected exactly {{{want}}}')
    print(f'{len(ROWS)} exemplars verified against registry v{reg.version}',
          file=sys.stderr)


def latex(reg) -> str:
    lines = [
        r'% GENERATED by accelscan/scripts/matching_table.py -- do not hand-edit.',
        r'% Every exemplar is run through the live matcher before this file is',
        r'% written, so the table cannot drift from registry.py.',
        r'\begin{table}[t]',
        r'\centering\small',
        r'\caption{Alias-matching conventions, each with an exemplar and the '
        r'entry it resolves to. Every exemplar carries GPU context, so a row '
        r'resolving to no model does so because of the convention under test and '
        r'not an unsatisfied context gate. Generated and verified against the live '
        r'matcher.}',
        r'\label{tab:matching-conventions}',
        r'\begin{tabular}{l l p{0.30\linewidth} l}',
        r'\hline',
        r'Convention & Alias & Passage & Resolves to \\',
        r'\hline',
    ]
    prev = None
    for name, alias, passage, want in ROWS:
        shown = '' if name == prev else name
        prev = name
        target = reg.models[want].display if want else r'\emph{no model}'
        lines.append(f'{shown} & \\texttt{{{alias}}} & {passage} & {target} \\\\')
    lines += [r'\hline', r'\end{tabular}', r'\end{table}', '']
    return '\n'.join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--stdout', action='store_true')
    ap.add_argument('--out', default=str(OUT_PATH))
    args = ap.parse_args()
    reg = load_registry()
    verify(reg)
    table = latex(reg)
    if args.stdout:
        print(table)
        return
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(table)
    print(f'wrote {out}', file=sys.stderr)


if __name__ == '__main__':
    main()
