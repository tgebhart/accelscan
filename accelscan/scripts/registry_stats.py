"""Registry composition numbers for the methods section, as a LaTeX table.

Every figure in the "Hardware registry" subsection's composition paragraph is a
function of the compiled registry, so it should be read out of the registry rather
than typed into prose and re-typed at every version bump. This emits both a
human-readable summary and `docs/tables/registry_composition.tex`, which
`docs/methods.tex` \\input's.

    python -m accelscan.scripts.registry_stats            # summary to stderr + write table
    python -m accelscan.scripts.registry_stats --stdout   # table to stdout, write nothing

The table is plain `tabular` + `\\hline` on purpose: the methods section is a
fragment dropped into a document whose preamble we do not control, so it must not
depend on booktabs, multirow or siunitx.
"""

import argparse
import sys
from collections import Counter
from pathlib import Path

from accelscan.registry import Model, load_registry

OUT_PATH = Path('docs/tables/registry_composition.tex')
# Manufacturers listed individually; the rest collapse into a counted tail row.
MIN_MODELS_LISTED = 10
SPEC_AXES = (('vram_gb', 'memory'), ('fp32_gflops', 'FP32'),
             ('fp64_gflops', 'FP64'), ('fp16_tensor_gflops', 'FP16 tensor'),
             ('tdp_w', 'TDP'))
SEGMENTS = ('datacenter', 'workstation', 'consumer', 'cloud')
VENDOR_LABEL = {'nvidia': 'NVIDIA', 'amd': 'AMD', 'intel': 'Intel',
                'apple': 'Apple', 'google': 'Google', 'huawei': 'Huawei',
                'cambricon': 'Cambricon', 'baidu': 'Baidu', 'amazon': 'AWS',
                'meta': 'Meta', 'microsoft': 'Microsoft', 'metax': 'MetaX',
                'biren': 'Biren', 'iluvatar': 'Iluvatar', 'tesla': 'Tesla',
                'sunway': 'Sunway', 'hygon': 'Hygon', 'alibaba': 'Alibaba',
                'pezy': 'PEZY', 'nudt': 'NUDT', 'moore-threads': 'Moore Threads',
                'unknown': 'unknown'}


def label(mfr: str) -> str:
    return VENDOR_LABEL.get(mfr, mfr.replace('-', ' ').title())


def release_span(models: list[Model]) -> str:
    years = sorted(int(m.release[:4]) for m in models if m.release)
    if not years:
        return '--'
    return f'{years[0]}' if years[0] == years[-1] else f'{years[0]}--{years[-1]}'


def collect(reg) -> dict:
    models = [m for m in reg.models.values() if m.kind == 'model']
    generic = [m for m in reg.models.values() if m.kind != 'model']
    by_mfr = Counter(m.manufacturer for m in models)

    listed = [k for k, n in by_mfr.most_common() if n >= MIN_MODELS_LISTED]
    tail = [k for k, n in by_mfr.most_common() if n < MIN_MODELS_LISTED]

    def row(name: str, ms: list[Model]) -> dict:
        return {
            'name': name, 'n': len(ms),
            'segments': {s: sum(m.segment == s for m in ms) for s in SEGMENTS},
            'release': release_span(ms),
            'specs': {f: sum(getattr(m, f) is not None for m in ms)
                      for f, _ in SPEC_AXES},
        }

    rows = [row(label(k), [m for m in models if m.manufacturer == k]) for k in listed]
    if tail:
        rows.append(row(f'{len(tail)} others', [m for m in models
                                                if m.manufacturer in tail]))
    return {
        'version': reg.version,
        'n_entries': len(reg.models), 'n_models': len(models),
        'n_generic': len(generic), 'n_manufacturers': len(by_mfr),
        'n_aliases': len(reg.aliases),
        'n_tier_b': sum(1 for a in reg.aliases if a.gate),
        'gates': {name: len(pat.pattern.split('|')) for name, pat in reg.gates.items()},
        'n_dated': sum(1 for m in models if m.release),
        'rows': rows, 'total': row('Total', models),
        'tail_names': sorted(label(k) for k in tail),
    }


def pct(n: int, d: int) -> str:
    return f'{100 * n / d:.1f}' if d else '--'


def latex(st: dict) -> str:
    cols = 'l r ' + 'r ' * len(SEGMENTS) + 'c ' + 'r ' * len(SPEC_AXES)
    seg_label = {'datacenter': 'DC', 'workstation': 'WS', 'consumer': 'Cons.',
                 'cloud': 'Cloud'}
    head_seg = ' & '.join(seg_label[s] for s in SEGMENTS)
    head_spec = ' & '.join(name for _, name in SPEC_AXES)
    lines = [
        r'% GENERATED by accelscan/scripts/registry_stats.py -- do not hand-edit.',
        r'% \input{tables/registry_composition} from docs/methods.tex; adjust the',
        r'% path if the methods fragment is included from a different directory.',
        r'\begin{table}[t]',
        r'\centering\small',
        rf'\caption{{Hardware registry v{st["version"]} composition. '
        r'Segment columns count model entries; specification columns give the '
        r"percentage of that vendor's models carrying a scraped "
        r'per-device figure on that axis. Missing figures stay null and are '
        r'excluded per axis rather than zero-filled.}',
        r'\label{tab:registry-composition}',
        rf'\begin{{tabular}}{{{cols.strip()}}}',
        r'\hline',
        r' & & \multicolumn{%d}{c}{Segment} & Release & '
        r'\multicolumn{%d}{c}{Specification coverage (\%%)} \\'
        % (len(SEGMENTS), len(SPEC_AXES)),
        rf'Vendor & Models & {head_seg} & years & {head_spec} \\',
        r'\hline',
    ]
    for r in st['rows'] + [st['total']]:
        if r['name'] == 'Total':
            lines.append(r'\hline')
        seg = ' & '.join(str(r['segments'][s]) for s in SEGMENTS)
        spec = ' & '.join(pct(r['specs'][f], r['n']) for f, _ in SPEC_AXES)
        lines.append(f'{r["name"]} & {r["n"]:,} & {seg} & {r["release"]} & '
                     f'{spec} \\\\')
    gates = ', '.join(f'\\texttt{{{k}}} {v}' for k, v in sorted(st['gates'].items()))
    lines += [
        r'\hline',
        r'\end{tabular}',
        r'',
        r'\vspace{0.5em}',
        rf'\parbox{{\linewidth}}{{\small The registry also carries '
        rf'{st["n_generic"]} generic entries (\texttt{{GPU}}, \texttt{{CUDA}}, '
        rf'\texttt{{TPU}}, \ldots\ and the two vendor brand triggers), for '
        rf'{st["n_entries"]:,} entries in total, and {st["n_aliases"]:,} aliases of '
        rf'which {st["n_tier_b"]} are tier~B (context-gated). Gate vocabulary '
        rf'sizes: {gates}. Release dates are populated for '
        rf'{st["n_dated"]:,} of {st["n_models"]:,} models.}}',
        r'\end{table}',
        '',
    ]
    return '\n'.join(lines)


def summary(st: dict) -> str:
    out = [f'registry v{st["version"]}: {st["n_entries"]:,} entries = '
           f'{st["n_models"]:,} models + {st["n_generic"]} generic | '
           f'{st["n_manufacturers"]} manufacturers | {st["n_aliases"]:,} aliases '
           f'({st["n_tier_b"]} tier B) | dated {st["n_dated"]:,}/{st["n_models"]:,}']
    for r in st['rows'] + [st['total']]:
        segs = ' '.join(f'{s[:4]}={r["segments"][s]}' for s in SEGMENTS)
        specs = ' '.join(f'{n}={pct(r["specs"][f], r["n"])}%' for f, n in SPEC_AXES)
        out.append(f'  {r["name"]:<14} n={r["n"]:<5} {segs:<40} {r["release"]:<10} {specs}')
    out.append(f'  tail: {", ".join(st["tail_names"])}')
    return '\n'.join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--stdout', action='store_true', help='print table, write nothing')
    ap.add_argument('--out', default=str(OUT_PATH))
    args = ap.parse_args()

    st = collect(load_registry())
    table = latex(st)
    print(summary(st), file=sys.stderr)
    if args.stdout:
        print(table)
        return
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(table)
    print(f'wrote {out}', file=sys.stderr)


if __name__ == '__main__':
    main()
