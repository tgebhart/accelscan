"""Derive notebooks/arxiv/*.ipynb from the S2ORC originals.

Generated, not hand-copied, for the same reason the registry is: hand-duplicating six
notebooks is how the missing `plt.show()` and the 100x-wrong percent formatter got in.
Rerun this after editing an S2ORC notebook and the arXiv twin follows instead of
drifting. **Every rule asserts that it matched**, so a rule that silently stops
applying because a cell was reworded is a hard error rather than a no-op.

  python -m accelscan.scripts.make_arxiv_notebooks
  python -m accelscan.scripts.make_arxiv_notebooks --only capacity

What changes, and why:

- `setup_figures('arxiv/<nb>')` -> figures land in output/analysis/arxiv/<nb>/ instead
  of overwriting the S2ORC ones.
- `YEAR_MIN, YEAR_MAX = 2005, 2026`. arXiv only: a paper is in the source tars the
  month it is submitted, so 2026 is real data, whereas S2ORC's 2026 holds 8% of a
  year's papers and would be pure ingestion artefact. 2026 is still partial, so mark
  it on count-based figures.
- `'corpusid'` -> `KEY` everywhere in code. arXiv's key is `paper_id`
  (`arxiv:2301.01234`) and its `corpusid` column is null by design.
- S3 paths go through `accelscan.paths` builders instead of f-strings over
  `OUT_PREFIX`, which is what puts them under `accelscan/arxiv/`.
- Field/year enrichment goes through `meta.paper_fields`, because arXiv has no
  `s2fieldsofstudy` -- `field` comes from arXiv's own taxonomy and is already a
  column, and `primary_category` has no S2ORC analogue.
- `productivity` loses §6.4 and the citation half of rank-stability: there is no
  arXiv->S2 crosswalk, so no forward citations. Half-life and adoption lag survive,
  since they need only year and model.
- A caveat cell is prepended to every notebook: preprint self-selection,
  physics/CS skew, and raw-LaTeX matching that reads captions and comments -- so
  arXiv levels are biased upward relative to S2ORC and only within-corpus trends are
  comparable.
"""

