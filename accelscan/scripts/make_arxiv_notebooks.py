# Cells removed wholesale: the citation section and the citation half of rank-stability.
DROP_CELLS = {'productivity': (18, 19, 20, 21)}


def transform(nb: str) -> dict:
    d = json.loads((SRC / f'{nb}.ipynb').read_text())
    for i in sorted(DROP_CELLS.get(nb, ()), reverse=True):
        del d['cells'][i]

    # notebook-specific rules first: several contain the generic analytic
    # f-string, and letting the generic rule fire first would stop them matching
    rules = list(RULES.get(nb, [])) + list(RULES[None])
    rules.append((f"setup_figures('{nb}')", f"setup_figures('arxiv/{nb}')"))
    md_rules = list(MD_RULES.get(nb, [])) + list(MD_RULES[None])
    counts = {r[0]: 0 for r in rules + md_rules}
    optional = {r[0] for r in rules + md_rules if len(r) > 2}
    for cell in d['cells']:
        if cell['cell_type'] != 'code':
            md = ''.join(cell['source'])
            for old, new, *_ in md_rules:
                if old in md:
                    counts[old] += md.count(old)
                    md = md.replace(old, new)
            md = md.replace('`s2fieldsofstudy`', "arXiv's own taxonomy")
            cell['source'] = md.replace('s2fieldsofstudy',
                                        'arXiv category').splitlines(keepends=True)
            continue
        src = ''.join(cell['source'])
        for old, new, *_ in rules:
            if old in src:
                counts[old] += src.count(old)
                src = src.replace(old, new)
        if '%%PLOTTING%%' in src:
            head, rest = src.split('%%PLOTTING%%', 1)
            names, tail = rest.split('\n', 1)
            src = (f'{head}from accelscan.plotting import {names}\n'
                   f'{IMPORTS}{tail}')
        src = src.replace("'corpusid'", 'KEY').replace('"corpusid"', 'KEY')
        # prose/comments: the taxonomy is arXiv's, not S2's. Runs after the rules
        # above, whose patterns still contain the literal column name.
        src = src.replace('`s2fieldsofstudy`', "arXiv's own taxonomy")
        src = src.replace('s2fieldsofstudy', 'arXiv category')
        cell['source'] = src.splitlines(keepends=True)
        cell['outputs'], cell['execution_count'] = [], None

    unmatched = [o for o, n in counts.items() if n == 0 and o not in optional]
    if unmatched:
        raise SystemExit(f'{nb}: {len(unmatched)} rule(s) matched nothing -- the source '
                         f'notebook changed:\n  ' + '\n  '.join(repr(u[:70])
                                                               for u in unmatched))
    # Outcome check, stronger than per-rule matching: no S2ORC-only reference may
    # survive. A path left over on OUT_PREFIX would silently read the S2ORC table.
    for i, cell in enumerate(d['cells']):
        if cell['cell_type'] != 'code':
            continue
        body = ''.join(cell['source'])
        for bad in ('{OUT_PREFIX}', 'PAPERS_PREFIX', "'corpusid'", '"corpusid"',
                    's2fieldsofstudy',
                    'mentions_glob(MODEL_TAG, PROMPT_VERSION)'):
            if bad in body:
                raise SystemExit(f'{nb}: cell {i} still references {bad!r} after '
                                 f'transformation')
    d['cells'].insert(0, {'cell_type': 'markdown', 'metadata': {},
                          'source': CAVEAT.splitlines(keepends=True)})
    return d


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--only', nargs='*', default=NOTEBOOKS)
    args = ap.parse_args()
    DST.mkdir(parents=True, exist_ok=True)
    for nb in args.only:
        d = transform(nb)
        out = DST / f'{nb}.ipynb'
        out.write_text(json.dumps(d, indent=1) + '\n')
        print(f'wrote {out} ({len(d["cells"])} cells)', file=sys.stderr)


if __name__ == '__main__':
    main()
